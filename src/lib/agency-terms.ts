export function getAgencyTerms(lang: string) {
  return lang?.startsWith('pt') ? PT : EN;
}

export async function hashTerms(text: string) {
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return Array.from(new Uint8Array(buf)).map(b => b.toString(16).padStart(2, '0')).join('');
}

export function downloadAgencyTerms(lang: string) {
  const blob = new Blob([getAgencyTerms(lang)], { type: 'text/plain;charset=utf-8' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = `adscale-agency-terms-${AGENCY_TERMS_VERSION}-${lang.startsWith('pt') ? 'pt' : 'en'}.txt`;
  a.click();
  URL.revokeObjectURL(a.href);
}
